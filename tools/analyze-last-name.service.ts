export function analyzeLastNameMixups(competitors: Competitor[]): void {
  const suspect: string[] = [];
  for (const c of competitors) {
    const firstNames = c.firstName.split(' ');
    if (lastNames.has(firstNames[0])) {
      const fixedFirst = `${[...firstNames.slice(1), c.lastName].join(' ')}`;
      const fixedLast = firstNames[0];
      suspect.push(`['${c.firstName} ${c.lastName}', { firstName: '${fixedFirst}', lastName: '${fixedLast}' }]`);
    }
  }

  fs.writeFileSync(`data/suspect-first-names.jsonl`, suspect.join('\n'), { encoding: 'utf-8' });
}
